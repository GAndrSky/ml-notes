// Builds shared-review-data.js: every self-check question (ml-quiz) of every lesson, in course order.
// usage: node scripts/build-review-data.mjs   (run from the repo root; no dependencies)
// Card ids are a hash of lesson path + question text, so review progress survives reordering.
import fs from 'node:fs';
import vm from 'node:vm';

const ctx = { window: {} };
vm.runInNewContext(fs.readFileSync('course-manifest.js', 'utf8'), ctx);
const sections = ctx.window.__mlNotesCourse.sections;

const fnv = (s) => { let h = 0x811c9dc5; for (const ch of s) { h ^= ch.codePointAt(0); h = Math.imul(h, 0x01000193) >>> 0; } return h.toString(36); };
const clean = (html) => html.replace(/\s+/g, ' ').trim();
const cards = [];
for (const section of sections) {
  for (const page of section.pages) {
    const html = fs.readFileSync(page.path, 'utf8');
    const re = /<summary class="ml-quiz__q">([\s\S]*?)<\/summary>\s*<div class="ml-quiz__a">([\s\S]*?)<\/div>\s*<\/details>/g;
    let m;
    while ((m = re.exec(html))) {
      const q = clean(m[1]);
      cards.push({ id: fnv(page.path + '|' + q.replace(/<[^>]+>/g, '')), path: page.path, label: page.label, section: section.id, q, a: clean(m[2]) });
    }
  }
}
const ids = new Set(cards.map((c) => c.id));
if (ids.size !== cards.length) throw new Error('duplicate card ids');
const sectionList = sections.map((s) => ({ id: s.id, label: s.label, title: s.title }));
fs.writeFileSync('shared-review-data.js',
  '// Generated by scripts/build-review-data.mjs - do not edit by hand.\n' +
  'window.__mlNotesReview = ' + JSON.stringify({ sections: sectionList, cards }) + ';\n');
console.log(`Review data rebuilt: ${cards.length} cards from ${new Set(cards.map((c) => c.path)).size} lessons.`);
